constexpr const ReaderOutputSpec* FindReaderOutputByStem(std::string_view stem) {
    for (std::size_t i = 0; i < kReaderOutputCatalog.size(); ++i) {
        if (kReaderOutputCatalog[i].stem == stem) return &kReaderOutputCatalog[i];
    }
    return nullptr;
}

constexpr std::size_t ReaderOutputTrailingElements(const ReaderOutputSpec& spec) {
    switch (spec.rank) {
    case ReaderOutputRank::Rank1:
        return 1;
    case ReaderOutputRank::Rank2:
        return spec.extent0;
    case ReaderOutputRank::Rank3:
        return spec.extent0 * spec.extent1;
    }
    return 0;
}

constexpr std::string_view ReaderOutputProducerName(ReaderOutputProducer producer) {
    switch (producer) {
    case ReaderOutputProducer::RingCurrent:
        return "RingCurrentNeighborhood/RecordSink";
    case ReaderOutputProducer::McConnell:
        return "McConnellNeighborhood/RecordSink";
    case ReaderOutputProducer::ChargeDipole:
        return "ChargeDipoleNeighborhood/RecordSink";
    case ReaderOutputProducer::BroadBackbone:
        return "BroadBackboneSink";
    case ReaderOutputProducer::PerAtomSubstrate:
        return "PerAtomSubstrate";
    case ReaderOutputProducer::AllAtomEquivariant:
        return "AllAtomEquivariantSink";
    case ReaderOutputProducer::Efg:
        return "EfgFeatureSink";
    case ReaderOutputProducer::BuckinghamEfield:
        return "BuckinghamEfieldSink";
    case ReaderOutputProducer::Aimnet2Features:
        return "Aimnet2FeatureSink";
    }
    return "unknown";
}

